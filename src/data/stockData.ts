function genHistory(base: number, days = 30): { date: string; price: number }[] {
  const history = [];
  let price = base * 0.88;
  for (let i = days; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    price = price * (1 + (Math.random() - 0.47) * 0.04);
    history.push({ date: d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }), price: parseFloat(price.toFixed(2)) });
  }
  history[history.length - 1].price = base;
  return history;
}

